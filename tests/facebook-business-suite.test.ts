describe('storing which surface a tenant is on', () => {
  let db: Database;
  let t: TestTenant;

  beforeAll(async () => {
    db = await freshDb();
    t = await makeTenant(db, 'fbbiz');
  });

  afterAll(async () => { await db.close(); });

  it('keeps the asset id beside the Page id, not instead of it', async () => {
    await withTenant(db, t.tenantId, (tx) =>
      setFbBridgeConnection({ tx, tenantId: t.tenantId, kek: TEST_KEK }, {
        status: 'ready', pageId: PAGE.id, pageName: PAGE.name, assetId: PAGE.assetId, actorId: null,
      }));

    const stored = await withTenant(db, t.tenantId, (tx) =>
      getFbBridgeConnection({ tx, tenantId: t.tenantId, kek: TEST_KEK }));

    expect(stored.pageId).toBe(PAGE.id);
    expect(stored.assetId).toBe(PAGE.assetId);
    expect(stored.assetId).not.toBe(stored.pageId);
  });

  it('does not blank the asset id on an ordinary status change', async () => {
    // A session expiring must not silently move the tenant back to reading a
    // personal inbox.
    await withTenant(db, t.tenantId, (tx) =>
      setFbBridgeConnection({ tx, tenantId: t.tenantId, kek: TEST_KEK }, {
        status: 'error', lastError: 'sesi habis', actorId: null,
      }));

    const stored = await withTenant(db, t.tenantId, (tx) =>
      getFbBridgeConnection({ tx, tenantId: t.tenantId, kek: TEST_KEK }));

    expect(stored.status).toBe('error');
    expect(stored.assetId).toBe(PAGE.assetId);
  });

  it('clears it when a Page is reconnected as a personal account', async () => {
    await withTenant(db, t.tenantId, (tx) =>
      setFbBridgeConnection({ tx, tenantId: t.tenantId, kek: TEST_KEK }, {
        status: 'ready', pageId: PAGE.id, pageName: PAGE.name, assetId: null, actorId: null,
      }));

    const stored = await withTenant(db, t.tenantId, (tx) =>
      getFbBridgeConnection({ tx, tenantId: t.tenantId, kek: TEST_KEK }));

    expect(stored.assetId).toBeNull();
  });
});

/* ------------------------------------------ Business Suite into the CRM */

describe('a Business Suite conversation reaching the CRM', () => {
  let db: Database;
  let app: FastifyInstance;
  let t: TestTenant;
  let e: Env;

  const post = (body: unknown) => app.inject({
    method: 'POST', url: '/v1/webhooks/fb-bridge',
    headers: { authorization: `Bearer ${e.FB_BRIDGE_SECRET}`, 'content-type': 'application/json' },
    payload: JSON.stringify(body),
  });

  /** Exactly what the watcher emits for a parsed Business Suite transcript. */
  const eventsFromFixture = async () => {
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {
      contactName: CONTACT.name, selfName: PAGE.name,
    });
    return parsed.messages.map((m, seq) => ({
      event: 'message', tenantId: t.tenantId, at: new Date().toISOString(),
      message: {
        threadId: CONTACT.id, externalMessageId: m.externalMessageId,
        senderId: CONTACT.id, senderName: m.senderName, text: m.text,
        sentAt: m.sentAt, direction: m.direction, seq,
      },
    }));
  };

  const storedMessages = () => withTenant(db, t.tenantId, (tx) =>
    tx.query<{ direction: string; sender_type: string; provider_message_id: string }>(
      `select m.direction, m.sender_type, m.provider_message_id
         from messages m join channels ch on ch.id = m.channel_id and ch.tenant_id = m.tenant_id
        where m.tenant_id = $1 and ch.kind = 'messenger_bridge'
        order by m.provider_message_id`,
      [t.tenantId]));

  beforeAll(async () => {
    db = await freshDb();
    t = await makeTenant(db, 'fbbizingest');
    e = env();

    app = buildApp({
      db, control: db, kek: TEST_KEK, env: e,
      dispatch: async ({ queue, payload }) => {
        if (queue !== 'inbound.normalise') return;
        await processInboundWebhook(
          { db, control: db, kek: TEST_KEK, dispatch: async () => {} },
          (payload as { webhookEventId: string }).webhookEventId,
        );
      },
    });
    await app.ready();

    await withTenant(db, t.tenantId, (tx) =>
      ensureMessengerBridgeChannel({ tx, tenantId: t.tenantId, kek: TEST_KEK }, {
        pageId: PAGE.id, pageName: PAGE.name, status: 'connected',
      }));
  });

  afterAll(async () => { await app.close(); await db.close(); });

  it('stores what the customer said as inbound', async () => {
    for (const ev of await eventsFromFixture()) {
      expect((await post(ev)).statusCode).toBe(200);
    }

    const inbound = (await storedMessages()).filter((r) => r.direction === 'inbound');

    expect(inbound).toHaveLength(2);
    expect(inbound.every((r) => r.sender_type === 'contact')).toBe(true);
  });

  it('stores the Page\'s own past reply as outbound history, not as a customer message', async () => {
    const outbound = (await storedMessages()).filter((r) => r.direction === 'outbound');

    expect(outbound).toHaveLength(1);
    expect(outbound[0]!.sender_type).not.toBe('contact');
  });

  it('adds nothing on a second reconciliation of the same thread', async () => {
    const before = (await storedMessages()).length;

    for (const ev of await eventsFromFixture()) {
      expect((await post(ev)).statusCode).toBe(200);
    }

    expect((await storedMessages()).length).toBe(before);
  });

  it('never stores the message the measurement could not read', async () => {
    const rows = await storedMessages();

    expect(rows.some((r) => r.provider_message_id.includes('synthetic0005'))).toBe(false);
  });
});

