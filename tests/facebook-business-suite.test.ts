/* ------------------------------------------------ the measurement layer */

describe('measuring which way a Business Suite message went', () => {
  it('reads flex-start as inbound and flex-end as outbound', () => {
    expect(JUSTIFY_DIRECTION['flex-start']).toBe('inbound');
    expect(JUSTIFY_DIRECTION['flex-end']).toBe('outbound');
  });

  it('puts that same table into the program that actually runs on the page', () => {
    // The in-page half cannot import anything, so the rule is interpolated
    // rather than shared. This is what stops the two copies drifting apart —
    // and a drifted copy files an agent's reply as the customer's.
    const script = buildAnnotatorScript(['div[role="region"]'], '[data-message-id]');
    expect(script).toContain(JSON.stringify(JUSTIFY_DIRECTION));
    expect(script).toContain(JSON.stringify(DIRECTION_ATTR));
  });

  it('never keys on a Facebook class hash', () => {
    // `x1nhvcw1` and `x13a6bvl` were the two atomic classes that differed
    // between an inbound and an outbound wrapper on the day this was probed.
    // They are regenerated by Facebook's own build, so neither may appear.
    const script = buildAnnotatorScript(['div[role="region"]'], '[data-message-id]');
    expect(script).not.toMatch(/\bx[0-9a-z]{6,8}\b/);
  });

  it('annotates a copy, never the live page', () => {
    const script = buildAnnotatorScript(['div[role="region"]'], '[data-message-id]');
    expect(script).toContain('cloneNode(true)');
    expect(script.match(/setAttribute/g)).toHaveLength(1);
    expect(script).toMatch(/copies\[j\]\.setAttribute/);
  });
});

/* ------------------------------------------------------------- parsers */

describe('the Business Suite transcript parser', () => {
  it('takes direction from the stamp and nothing else', async () => {
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {
      contactName: CONTACT.name, selfName: PAGE.name,
    });

    expect(parsed.messages.map((m) => m.direction)).toEqual(['inbound', 'outbound', 'inbound']);
  });

  it('does not confuse an outbound message with an inbound one of identical text', async () => {
    // The fixture says "halo kak" twice, once each way. Anything keyed on the
    // words rather than on the stamp collapses these two.
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {
      contactName: CONTACT.name, selfName: PAGE.name,
    });
    const halo = parsed.messages.filter((m) => m.text === 'halo kak');

    expect(halo).toHaveLength(2);
    expect(halo.map((m) => m.direction)).toEqual(['inbound', 'outbound']);
    expect(new Set(halo.map((m) => m.externalMessageId)).size).toBe(2);
  });

  it('drops a message the measurement could not read, and says how many', async () => {
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {
      contactName: CONTACT.name, selfName: PAGE.name,
    });

    expect(parsed.messages.map((m) => m.text)).not.toContain('ini tidak boleh ikut masuk');
    expect(parsed.unknownSenderRows).toBe(1);
  });

  it('keeps Facebook\'s own message id, in the shape messenger.com also uses', async () => {
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {});

    expect(parsed.messages.every((m) => m.externalMessageId?.startsWith('mid.$'))).toBe(true);
    // The shared shape is the whole reason one idempotency key covers both
    // surfaces: the same conversation read from either cannot be stored twice.
    expect(parsed.messages[0]!.externalMessageId).toBe('mid.$cAAQAAsynthetic0001');
  });

  it('names the sender from the conversation, because the bubbles name nobody', async () => {
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {
      contactName: CONTACT.name, selfName: PAGE.name,
    });

    expect(parsed.messages[0]!.senderName).toBe(CONTACT.name);
    expect(parsed.messages[1]!.senderName).toBe(PAGE.name);
  });

  it('reads the timestamp off the group wrapper', async () => {
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {});

    expect(parsed.messages[0]!.sentAt).toBe(new Date(1758546240 * 1000).toISOString());
  });

  it('skips a sticker rather than ingesting a blank message', async () => {
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {});

    expect(parsed.messages.every((m) => m.text.trim().length > 0)).toBe(true);
    // The empty bubble is not a failure either — it must not inflate the count
    // that tells an operator the selectors went stale.
    expect(parsed.unknownSenderRows).toBe(1);
  });

  it('hands the live watcher inbound only', async () => {
    const parsed = parseBusinessSuiteThread(await fixture('business-suite-thread.html'), {
      contactName: CONTACT.name, selfName: PAGE.name,
    });

    expect(parsed.messages.map((m) => m.text)).toEqual(['halo kak', 'mau tanya harga']);
    expect(parsed.outboundRows).toBe(1);
  });

  it('reads the contact name out of the conversation header', () => {
    const header = '<span data-surface="/bizweb:inbox/lib:inbox:detail_view_header">'
      + '<div>Sinta</div><div>Assign this conversation</div></span>';

    expect(parseBusinessSuiteHeaderName(header)).toBe('Sinta');
  });

  // Live capture. Business Suite nests the name and the two header buttons
  // under a chain of wrappers that each repeat their children's text, so a
  // reading that keeps ancestors hands back "GabeAssign this conversationOpen
  // Drop-down" as the contact's name. That is not cosmetic: the inbox sweep
  // confirms it selected the right row by comparing this name to the row's
  // title, so while it was wrong NO conversation could be read at all.
  it('reads the contact name out of the real nested header', async () => {
    expect(parseBusinessSuiteHeaderName(await fixture('business-suite-header.html'))).toBe('Gabe');
  });

  it('drops a wrapper that only repeats its children, keeps one that adds text', () => {
    const repeats = '<span data-surface="lib:inbox:detail_view_header">'
      + '<div><div>Sinta</div><div>Assign this conversation</div></div></span>';
    const adds = '<span data-surface="lib:inbox:detail_view_header">'
      + '<div>Sinta <div>Assign this conversation</div></div></span>';

    expect(parseBusinessSuiteHeaderName(repeats)).toBe('Sinta');
    expect(parseBusinessSuiteHeaderName(adds)).toBe('Sinta Assign this conversation');
  });

  // A zero-width space is not whitespace to `String.trim`, and Business Suite
  // renders one at the end of the header. Left in, it makes two readings of the
  // same name compare unequal.
  it('treats a zero-width space as nothing', () => {
    const header = '<span data-surface="lib:inbox:detail_view_header">'
      + '<div>Sinta\u200b</div></span>';

    expect(parseBusinessSuiteHeaderName(header)).toBe('Sinta');
  });
});

describe('confirming a Business Suite send', () => {
  it('counts only our own messages carrying exactly that text', async () => {
    const html = await fixture('business-suite-thread.html');

    expect(countOwnBusinessSuiteMessages(html, { text: 'halo kak' })).toBe(1);
    expect(countOwnBusinessSuiteMessages(html, { text: 'mau tanya harga' })).toBe(0);
    expect(countOwnBusinessSuiteMessages(html, { text: 'belum pernah dikirim' })).toBe(0);
  });

  it('is a count, so success needs a NEW bubble rather than a matching one', async () => {
    const html = await fixture('business-suite-thread.html');
    const before = countOwnBusinessSuiteMessages(html, { text: 'halo kak' });
    // A second identical reply arrives. "Is our text on screen?" was already
    // true before it was sent; only the count moving proves anything.
    const after = countOwnBusinessSuiteMessages(
      html.replace(
        `<div data-message-id="mid.$cAAQAAsynthetic0003" ${DIRECTION_ATTR}="inbound">mau tanya harga</div>`,
        `<div data-message-id="mid.$cAAQAAsynthetic0006" ${DIRECTION_ATTR}="outbound">halo kak</div>`,
      ),
      { text: 'halo kak' },
    );

    expect(before).toBe(1);
    expect(after).toBe(2);
  });

  // The CRM types a reply with line breaks and an emoji; the page shows it back
  // as one run per line with nothing between them and the emoji as a picture.
  // Compared raw, a multi-line reply was never seen as sent — and was failed as
  // unconfirmed after Facebook had already delivered it.
  it('recognises a multi-line reply with an emoji however the page lays it out', async () => {
    const html = await fixture('business-suite-thread.html');
    const anchor = `<div data-message-id="mid.$cAAQAAsynthetic0003" ${DIRECTION_ATTR}="inbound">mau tanya harga</div>`;
    const sent = 'Halo, Kak, salam kenal 😊\nSaya Grace dari MCNAsia.biz.\n\nBoleh dibantu isi data berikut?';
    const bubble = (direction: string) => `<div data-message-id="mid.$cAAQAAsynthetic0007" ${DIRECTION_ATTR}="${direction}">`
      + '<div dir="auto">Halo, Kak, salam kenal <img alt="😊" src="e.png"></div>'
      + '<div dir="auto">Saya Grace dari MCNAsia.biz.</div><div dir="auto">Boleh dibantu isi data berikut?</div></div>';
    expect(html).toContain(anchor);

    expect(countOwnBusinessSuiteMessages(html, { text: sent })).toBe(0);
    expect(countOwnBusinessSuiteMessages(html.replace(anchor, anchor + bubble('outbound')), { text: sent })).toBe(1);
    // Still only our own side, and still only these words.
    expect(countOwnBusinessSuiteMessages(html.replace(anchor, anchor + bubble('inbound')), { text: sent })).toBe(0);
    expect(countOwnBusinessSuiteMessages(html.replace(anchor, anchor + bubble('outbound')), {
      text: 'Saya Grace dari MCNAsia.biz.',
    })).toBe(0);
  });
});

describe('reconciling a Business Suite thread more than once', () => {
  it('imports nothing the second time', async () => {
    const parsed = parseBusinessSuiteTranscript(await fixture('business-suite-thread.html'), {
      contactName: CONTACT.name, selfName: PAGE.name,
    });

    const stored = new Set<string>();
    const first = selectBackfill(parsed.messages, { isKnown: (id) => stored.has(id), maxMessages: 50 });
    for (const m of first) stored.add(m.externalMessageId!);
    const second = selectBackfill(parsed.messages, { isKnown: (id) => stored.has(id), maxMessages: 50 });

    expect(first).toHaveLength(3);
    expect(second).toHaveLength(0);
  });

  it('imports only what is genuinely new when the thread grows', async () => {
    const html = await fixture('business-suite-thread.html');
    const before = parseBusinessSuiteTranscript(html, {});
    const stored = new Set(before.messages.map((m) => m.externalMessageId!));

    const grown = parseBusinessSuiteTranscript(
      html.replace(
        '    </div>\n  </div>\n</div>',
        '      <div data-utime="1758546540"><div><div><div><div>'
        + `<div data-message-id="mid.$cAAQAAsynthetic0007" ${DIRECTION_ATTR}="inbound">masih ada?</div>`
        + '</div></div></div></div></div>\n    </div>\n  </div>\n</div>',
      ),
      {},
    );
    const missing = selectBackfill(grown.messages, { isKnown: (id) => stored.has(id), maxMessages: 50 });

    expect(missing.map((m) => m.text)).toEqual(['masih ada?']);
  });
});

