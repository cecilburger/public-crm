describe('choosing a transport', () => {
  it('builds Business Suite URLs from the asset id, never the Page id', () => {
    const ctx = { pageName: PAGE.name, assetId: PAGE.assetId };

    expect(businessSuiteTransport.inboxUrl(ctx)).toContain(`asset_id=${PAGE.assetId}`);
    expect(businessSuiteTransport.inboxUrl(ctx)).not.toContain(PAGE.id);
    expect(businessSuiteTransport.threadUrl(ctx, CONTACT.id))
      .toBe('https://business.facebook.com/latest/inbox/all'
        + `?asset_id=${PAGE.assetId}&selected_item_id=${CONTACT.id}&thread_type=FB_MESSAGE`);
  });

  it('refuses to navigate at all without an asset id', () => {
    // Better one loud error at the first navigation than a browser sitting on a
    // valid-looking Business Suite page holding nobody's conversations.
    expect(() => businessSuiteTransport.inboxUrl({ pageName: PAGE.name, assetId: null }))
      .toThrow(/asset id/i);
  });

  it('can enumerate an inbox on both surfaces', () => {
    // Business Suite gets there by click-to-reveal; messenger.com reads hrefs.
    // Either way the watcher may trust that a new conversation will be found.
    expect(businessSuiteTransport.discoversConversations).toBe(true);
    expect(messengerDotComTransport.discoversConversations).toBe(true);
  });

  it('leaves the messenger.com transport exactly as it was', async () => {
    const ctx = { pageName: PAGE.name, assetId: null };
    expect(messengerDotComTransport.inboxUrl(ctx)).toBe('https://www.facebook.com/messages/t/');
    expect(messengerDotComTransport.threadUrl(ctx, CONTACT.id))
      .toBe(`https://www.facebook.com/messages/t/${CONTACT.id}/`);

    // And it still reads the old fixture the way it always did — the Page work
    // must not have quietly changed what a personal inbox parses to.
    const html = await fixture('messenger-thread.html');
    const viaTransport = messengerDotComTransport.parseThread(html, { selfName: PAGE.name });
    const direct = parseMessengerThread(html, { selfName: PAGE.name });

    expect(viaTransport).toEqual(direct);
  });
});

